import { execFileSync } from 'node:child_process';
import {
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync
} from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

function parseTauriCommandNames(projectRoot) {
  const registryPath = path.join(
    projectRoot,
    'src-tauri/src/commands/registry.rs'
  );
  const source = readFileSync(registryPath, 'utf8');
  const productionSource = source.split('#[cfg(test)]')[0];
  const listMarker = '$macro! {';
  const listStart = productionSource.indexOf(listMarker);
  if (listStart === -1) {
    throw new Error(
      'Could not find with_commands command list in commands/registry.rs'
    );
  }
  const bodyContentStart = listStart + listMarker.length;
  const listEnd = productionSource.indexOf('\n        }', bodyContentStart);
  if (listEnd === -1) {
    throw new Error('Could not find with_commands command list end');
  }
  const block = productionSource.slice(bodyContentStart, listEnd);
  return block
    .split('\n')
    .map((line) => line.trim().replace(/[),]+$/, ''))
    .map((line) => line.split(',').pop()?.trim() ?? '')
    .filter((name) => /^[a-z][a-z0-9_]*$/.test(name));
}

function writeTauriCommandNames(projectRoot, commandNames) {
  const outPath = path.join(
    projectRoot,
    'src/types/generated/tauri-command-names.ts'
  );
  const union = commandNames.map((name) => `  | '${name}'`).join('\n');
  writeFileSync(
    outPath,
    `// Generated by scripts/generate-bindings.mjs\nexport const TAURI_COMMAND_NAMES = [\n${commandNames.map((name) => `  '${name}',`).join('\n')}\n] as const;\n\nexport type TauriCommandName =\n${union};\n`,
    'utf8'
  );
}

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(scriptDir, '..');
const generatedDir = path.join(projectRoot, 'src/types/generated');
const bindingsDir = path.join(generatedDir, 'bindings');
const barrelPath = path.join(generatedDir, 'index.ts');
const tauriBindingsDir = path.join(projectRoot, 'src-tauri/bindings');

mkdirSync(generatedDir, { recursive: true });
rmSync(bindingsDir, { recursive: true, force: true });
rmSync(tauriBindingsDir, { recursive: true, force: true });
mkdirSync(bindingsDir, { recursive: true });

execFileSync(
  'cargo',
  [
    'test',
    'export_bindings',
    '--manifest-path',
    'src-tauri/Cargo.toml',
    '--',
    '--nocapture'
  ],
  {
    cwd: projectRoot,
    stdio: 'inherit',
    env: {
      ...process.env,
      TS_RS_EXPORT_DIR: '../src/types/generated/bindings',
      TS_RS_LARGE_INT: 'number'
    }
  }
);

rmSync(tauriBindingsDir, { recursive: true, force: true });

const typeFiles = readdirSync(bindingsDir)
  .filter((name) => name.endsWith('.ts'))
  .sort((left, right) => left.localeCompare(right));

const exports = typeFiles.map((name) => {
  const typeName = path.basename(name, '.ts');
  return `export type { ${typeName} } from './bindings/${typeName}';`;
});

writeFileSync(
  barrelPath,
  `// Generated by scripts/generate-bindings.mjs\n${exports.join('\n')}\nexport type { TauriCommandName } from './tauri-command-names';\n`,
  'utf8'
);

writeTauriCommandNames(projectRoot, parseTauriCommandNames(projectRoot));
